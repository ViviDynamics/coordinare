from __future__ import annotations

import os
import shlex
from pathlib import Path
from typing import Any

ENV_FILENAME = "coordinare.env"
SECRET_MODE = 0o600
PRIVATE_DIRECTORY_MODE = 0o700
GENERATED_HEADER = "# Generated by coordinare init."


def expand_environment_values(value: Any) -> Any:
    """Expand parsed scalar values so credentials cannot become YAML syntax."""
    if isinstance(value, dict):
        return {key: expand_environment_values(item) for key, item in value.items()}
    if isinstance(value, list):
        return [expand_environment_values(item) for item in value]
    return os.path.expandvars(value) if isinstance(value, str) else value


def _xdg_directory(variable: str, fallback: Path) -> Path:
    value = os.environ.get(variable, "")
    root = Path(value) if value and Path(value).is_absolute() else fallback
    return root / "coordinare"


def user_config_directory() -> Path:
    return _xdg_directory("XDG_CONFIG_HOME", Path.home() / ".config")


def user_data_directory() -> Path:
    return _xdg_directory("XDG_DATA_HOME", Path.home() / ".local" / "share")


def read_environment(path: Path) -> dict[str, str]:
    """Read init's literal shell-quoted assignments without executing anything."""
    if not path.exists():
        return {}
    values = {}
    for line in path.read_text().splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        key, separator, value = line.partition("=")
        if not separator or not key.isidentifier():
            message = "Invalid coordinare.env assignment; rerun coordinare init."
            raise ValueError(message)
        try:
            parts = shlex.split(value)
        except ValueError:
            message = "Invalid coordinare.env quoting; rerun coordinare init."
            raise ValueError(message) from None
        if len(parts) > 1:
            message = "Invalid coordinare.env quoting; rerun coordinare init."
            raise ValueError(message)
        values[key] = parts[0] if parts else ""
    return values


def load_config_environment(config_path: Path) -> None:
    """Dedicated init secrets file only; exported variables retain precedence."""
    for key, value in read_environment(config_path.parent / ENV_FILENAME).items():
        os.environ.setdefault(key, value)
